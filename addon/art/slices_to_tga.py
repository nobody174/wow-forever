"""Turn a theme's PNG slices into the 32-bit TGA textures the game loads, and write the flag file that switches the image look on.

    python addon/art/slices_to_tga.py azeroth        # addon/art/sources/azeroth/*.png -> addon/RoadToForever/media/azeroth/*.tga + Images.lua

The game cannot read PNG. Every side must be a power of two (checked here). Alpha is kept as it is; fully transparent pixels get the
colour of their nearest opaque neighbour so a stretched or tiled edge shows no dark halo. `Images.lua` (generated, never hand-edit)
sets R2F.Images.<theme> = true for every theme whose folder has been converted; the addon only draws images for those.
"""
import os
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "art" / "sources"
MEDIA = ROOT / "RoadToForever" / "media"
POW2 = {32, 64, 128, 256, 512, 1024}
SMALL_OK = {8, 16}          # strips may be thin on one side (edge strips, divider)


def bleed(im):
    """Give transparent pixels the colour of a neighbour so filtering at the edge of a shape does not pull in black."""
    px = im.load()
    w, h = im.size
    done = [[px[x, y][3] > 0 for x in range(w)] for y in range(h)]
    for _ in range(4):
        grow = []
        for y in range(h):
            for x in range(w):
                if done[y][x]:
                    continue
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < w and 0 <= ny < h and done[ny][nx]:
                        r, g, b, _a = px[nx, ny]
                        grow.append((x, y, (r, g, b, 0)))
                        break
        for x, y, c in grow:
            px[x, y] = c
            done[y][x] = True
    return im


# The game shows these textures brighter than the PNGs (measured on screenshots of 0.71.0: texture value v is drawn as about
# 255 * (v / 255) ** 0.67). Pre-darken the colour channels by the inverse so the picture on screen matches the design. Alpha is
# untouched, pure white stays white. Per theme folder; 1.0 = off.
GAMMA = {"azeroth": 1.5}


def pre_darken(im, gamma):
    if gamma == 1.0:
        return im
    lut = [round(255 * (i / 255.0) ** gamma) for i in range(256)]
    r, g, b, a = im.split()
    return Image.merge("RGBA", (r.point(lut), g.point(lut), b.point(lut), a))


def convert(theme):
    src, out = SRC / theme, MEDIA / theme
    out.mkdir(parents=True, exist_ok=True)
    names = []
    for png in sorted(src.glob("*.png")):
        im = Image.open(png).convert("RGBA")
        w, h = im.size
        ok = lambda n: n in POW2 or n in SMALL_OK
        if not (ok(w) and ok(h)):
            raise SystemExit("%s is %dx%d: each side must be 8, 16, 32, 64, 128 or 256" % (png.name, w, h))
        pre_darken(bleed(im), GAMMA.get(theme, 1.0)).save(out / (png.stem + ".tga"), "TGA", orientation=1)
        names.append(png.stem)
    return names


def write_flags():
    themes = sorted(p.name for p in MEDIA.iterdir() if p.is_dir() and list(p.glob("*.tga")) and p.name != "fonts")
    lines = ["-- GENERATED by addon/art/slices_to_tga.py: which themes have their image slices in media/<theme>/. Never hand-edit.",
             "local _, R2F = ...", "", "R2F.Images = {"]
    lines += ["  %s = true," % t for t in themes]
    lines += ["}", ""]
    (ROOT / "RoadToForever" / "Images.lua").write_text("\n".join(lines), encoding="utf-8")
    return themes


if __name__ == "__main__":
    for theme in sys.argv[1:] or [d.name for d in SRC.iterdir() if d.is_dir()]:
        n = convert(theme)
        print("%s: %d textures" % (theme, len(n)))
    print("images on for:", ", ".join(write_flags()))
