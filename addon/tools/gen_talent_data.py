#!/usr/bin/env python3
"""Writes addon/RoadToForever/TalentData.lua: every class's three talent trees (for the Talents tab's
sandbox calculator) plus our recommended builds (from builds.html).

The trees come from the same public Wowhead Forever script the site's talent calculator loads
(https://nether.wowhead.com/forever/data/talents-classic), so the addon shows the same talents,
descriptions and link digits as talents.html. The addon itself can't reach the internet, so the data is
a snapshot: rerun this script when Wowhead changes the trees or builds.html gets a new build.

    python addon/tools/gen_talent_data.py            # fetch + write
    python addon/tools/gen_talent_data.py --check    # exit 1 if builds.html's builds changed since the file was written

Never hand-edit TalentData.lua.
"""
import json
import re
import sys
import urllib.request
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "addon" / "RoadToForever" / "TalentData.lua"
URL = "https://nether.wowhead.com/forever/data/talents-classic"

# Same ids, tree ids and tab order as talentcalc.js CLASSES (the site's armor-type roster order).
CLASSES = [
    ("priest", "PRIEST", [(201, "Discipline"), (202, "Holy"), (203, "Shadow")]),
    ("warlock", "WARLOCK", [(302, "Affliction"), (303, "Demonology"), (301, "Destruction")]),
    ("mage", "MAGE", [(81, "Arcane"), (41, "Fire"), (61, "Frost")]),
    ("rogue", "ROGUE", [(182, "Assassination"), (181, "Combat"), (183, "Subtlety")]),
    ("druid", "DRUID", [(283, "Balance"), (281, "Feral Combat"), (282, "Restoration")]),
    ("shaman", "SHAMAN", [(261, "Elemental"), (263, "Enhancement"), (262, "Restoration")]),
    ("hunter", "HUNTER", [(361, "Beast Mastery"), (363, "Marksmanship"), (362, "Survival")]),
    ("paladin", "PALADIN", [(382, "Holy"), (383, "Protection"), (381, "Retribution")]),
    ("warrior", "WARRIOR", [(161, "Arms"), (164, "Fury"), (163, "Protection")]),
]


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ").replace("\r", "") + '"'


def clean(text):
    text = re.sub(r"<!--.*?-->", "", text)
    text = re.sub(r"<[^>]+>", "", text)
    return re.sub(r"\s+", " ", text).strip()


def fetch():
    req = urllib.request.Request(URL, headers={"User-Agent": "Mozilla/5.0"})
    text = urllib.request.urlopen(req, timeout=60).read().decode("utf-8")
    start = text.index('{"glyphs"')
    data, _ = json.JSONDecoder().raw_decode(text[start:])
    return data["talents"]


def builds():
    """Recommended builds from builds.html: (class id, level, role, title, code)."""
    html = (ROOT / "builds.html").read_text(encoding="utf-8")
    out = []
    for m in re.finditer(r'spec: "(.*?)", title: "(.*?)", code: "(.*?)"', html):
        spec, title, code = m.groups()
        cls = title.split()[0].lower()
        lvl = re.search(r"Level (\d+)", title)
        rest = re.sub(r"^.*?Level \d+\s*", "", title)
        if not lvl or cls not in [c[0] for c in CLASSES]:
            continue
        role = "Healer" if "(Healer" in title else "Tank" if "(Tank" in title or "tank" in title else "DPS"
        name = re.sub(r"\s*\((Healer|Tank|DPS)\)\s*$", "", rest).strip()
        out.append((cls, int(lvl.group(1)), role, name, code))
        if role == "Tank" and "Cat" in title:   # Feral (Bear tank / Cat): one spec, listed under both roles
            out.append((cls, int(lvl.group(1)), "DPS", name, code))
    return out


def trees_lua(raw, trees):
    """Lua lines for one class's trees: `trees` = [(tree id, name)], `raw` = Wowhead's {tree id: {talent id: talent}}.
    Also used by the tests to feed the addon a small fixture in the same format."""
    lines = []
    for tid, tname in trees:
        src = raw.get(str(tid), {})
        lst = sorted(src.values(), key=lambda x: (x["row"], x["col"]))
        index = {x["id"]: k + 1 for k, x in enumerate(lst)}
        lines.append("      { name = %s, talents = {" % lua_str(tname))
        for x in lst:
            q = ",".join("{%d,%d}" % (index[r["id"]], r["qty"]) for r in x.get("requires", []))
            descs = x.get("descriptions", {})
            d = ",".join(lua_str(clean(descs.get(str(i), ""))) for i in range(1, len(x["ranks"]) + 1))
            p = x.get("requiredPoints", x["row"] * 5)
            lines.append("        {n=%s,i=%s,r=%d,c=%d,m=%d,p=%d,q={%s},d={%s}}," % (
                lua_str(x["name"]), lua_str(x["icon"]), x["row"], x["col"], len(x["ranks"]), p, q, d))
        lines.append("      } },")
    return lines


def build_text(raw):
    lines = [
        "-- TalentData.lua: GENERATED by addon/tools/gen_talent_data.py. Never hand-edit.",
        "-- Every class's three talent trees (the same data the site's talent calculator uses, from Wowhead's",
        "-- Forever calculator script, snapshot %s) and our recommended builds (from builds.html)." % date.today().isoformat(),
        "-- Talents are in link order: sorted by row, then column, so digit k of a share code is talent k.",
        "-- n name, i icon file, r row (0-based), c column (0-based), m max rank, p points needed in the tree",
        "-- below it, q prerequisites {talent number in the same tree, ranks needed}, d one description per rank.",
        "",
        "local _, R2F = ...",
        "",
        "R2F.TalentData = {",
        "  classes = {",
    ]
    for cid, token, trees in CLASSES:
        lines.append("    %s = { token = %s, trees = {" % (cid, lua_str(token)))
        lines.extend(trees_lua(raw, trees))
        lines.append("    } },")
    lines.append("  },")
    lines.append("  -- Recommended builds: { class, level, role (Tank / DPS / Healer), name, code } (builds.html).")
    lines.append("  builds = {")
    for cls, lvl, role, name, code in builds():
        lines.append("    {%s,%d,%s,%s,%s}," % (lua_str(cls), lvl, lua_str(role), lua_str(name), lua_str(code)))
    lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    if "--check" in sys.argv:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        want = [("%s,%d,%s,%s,%s" % (c, l, r, n, k)) for c, l, r, n, k in builds()]
        got = re.findall(r'\{"(\w+)",(\d+),"(\w+)","(.*?)","(.*?)"\},', have)
        got = ["%s,%s,%s,%s,%s" % g for g in got]
        if want != got:
            print("TalentData.lua is out of date with builds.html: run python addon/tools/gen_talent_data.py")
            return 1
        return 0
    raw = fetch()
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(build_text(raw))
    print("wrote %s (%d bytes)" % (OUT, OUT.stat().st_size))
    return 0


if __name__ == "__main__":
    sys.exit(main())
