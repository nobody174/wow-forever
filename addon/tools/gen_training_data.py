#!/usr/bin/env python3
"""Generate addon/RoadToForever/TrainingData.lua: what each class trainer sells, by level (the Training tab's shipped list).

Source: Wowhead Forever's ability lists, https://www.wowhead.com/forever/spells/abilities/<class>
(the page's `listviewspells` table; rows with source 6 = sold by the class trainer, `trainingcost` in copper).
Wowhead blocks plain downloads, so the data is read in a browser and saved as one JSON file {class: [rows]}:
open any of those pages, then run in its console (it fetches the nine pages from the same origin and downloads wh_all.json):

    (async () => { const out = {};
      for (const s of ["warrior","paladin","hunter","rogue","priest","shaman","mage","warlock","druid"]) {
        const t = await (await fetch("/forever/spells/abilities/" + s)).text();
        const i = t.indexOf("listviewspells"); const a = t.indexOf("[", i); let d = 0, j = a;
        for (; j < t.length; j++) { if (t[j] === "[") d++; else if (t[j] === "]" && --d === 0) break; }
        out[s] = new Function("return " + t.slice(a, j + 1))().map(r => ({ id: r.id, name: r.name, level: r.level,
          rank: r.rank, trainingcost: r.trainingcost, source: r.source }));
      }
      const b = new Blob([JSON.stringify(out)]); const l = document.createElement("a");
      l.href = URL.createObjectURL(b); l.download = "wh_all.json"; l.click(); })();

Usage: python addon/tools/gen_training_data.py [path to wh_all.json]   (default: ~/Downloads/wh_all.json)
Costs are Wowhead's list price: the addon shows them as estimates and a visit to the trainer replaces them with the
real price (reputation discount included). Names and icons are read from the game by spell id at runtime.
"""
import datetime
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "RoadToForever", "TrainingData.lua")
CAP = 60


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.expanduser("~"), "Downloads", "wh_all.json")
    data = json.load(open(path, encoding="utf-8"))
    lines = [
        "-- TrainingData.lua: GENERATED by addon/tools/gen_training_data.py. Never hand-edit.",
        "-- What each class trainer sells, by level, from Wowhead Forever's ability lists (%s)." % datetime.date.today().isoformat(),
        "-- Row: { spell id, level, rank (0 = none), cost in copper (Wowhead's list price: an estimate), name }.",
        "-- Icons and tooltips are read from the game by spell id; a visit to the trainer replaces the cost with the real price.",
        "local _, R2F = ...",
        "R2F.TrainingData = {",
    ]
    for cls in ("warrior", "paladin", "hunter", "rogue", "priest", "shaman", "mage", "warlock", "druid"):
        rows, seen = [], set()
        for r in data.get(cls, []):
            if 6 not in (r.get("source") or []) or r["id"] in seen or not r.get("level") or r["level"] > CAP:
                continue
            seen.add(r["id"])
            m = re.search(r"(\d+)", r.get("rank") or "")
            rows.append((r["level"], r["name"], r["id"], int(m.group(1)) if m else 0, int(r.get("trainingcost") or 0)))
        rows.sort()
        lines.append("  %s = {" % cls.upper())
        for lvl, name, sid, rank, cost in rows:
            lines.append('    { %d, %d, %d, %d, "%s" },' % (sid, lvl, rank, cost, name.replace("\\", "\\\\").replace('"', '\\"')))
        lines.append("  },")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT, "(%d lines)" % len(lines))


if __name__ == "__main__":
    main()
