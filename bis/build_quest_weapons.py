"""Writes addon/RoadToForever/QuestWeaponData.lua from bis/quest-weapons.json (bis/tools/wh_quest_weapons.py).

One row per weapon, positional: { itemId, "name", "kind", requiredLevel, "quest", "zone", side, quality }
  kind    1h axe | 2h axe | 1h mace | 2h mace | 1h sword | 2h sword | dagger | staff | polearm | fist | bow | gun | crossbow | wand | thrown | shield
  side    0 = both factions, 1 = Alliance only, 2 = Horde only
  quality 2 = green, 3 = blue
Rows without a zone are left out (a quest with no zone cannot be matched to a plan step). The data is Wowhead Forever's, credited in the addon.
Also writes launch-plan-weapons.json for launch-plan.html (the same rows plus dps, and the class table).
Run by build.py; never edit QuestWeaponData.lua or launch-plan-weapons.json by hand.
"""
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "bis", "quest-weapons.json")
OUT = os.path.join(ROOT, "addon", "RoadToForever", "QuestWeaponData.lua")
OUT_SITE = os.path.join(ROOT, "launch-plan-weapons.json")

# Weapon kinds each class can use: Forever's proficiencies (ForeverDB "Trainers & weapon skills", checked 2026-10-17: it
# differs from Classic only in that Rogues can use one-handed axes). Dual wield is not modelled. THE one place for this
# table: QuestWeaponData.lua (`use`) and launch-plan-weapons.json both carry it from here.
CLASS_USE = {
    "WARRIOR": ["1h axe", "2h axe", "1h mace", "2h mace", "1h sword", "2h sword", "dagger", "fist", "polearm", "staff",
                "bow", "gun", "crossbow", "thrown", "shield"],
    "PALADIN": ["1h axe", "2h axe", "1h mace", "2h mace", "1h sword", "2h sword", "polearm", "shield"],
    "HUNTER": ["1h axe", "2h axe", "1h sword", "2h sword", "dagger", "fist", "polearm", "staff", "bow", "gun", "crossbow",
               "thrown"],
    "ROGUE": ["dagger", "fist", "1h axe", "1h mace", "1h sword", "bow", "gun", "crossbow", "thrown"],
    "PRIEST": ["dagger", "1h mace", "staff", "wand"],
    "MAGE": ["dagger", "1h sword", "staff", "wand"],
    "WARLOCK": ["dagger", "1h sword", "staff", "wand"],
    "DRUID": ["dagger", "fist", "1h mace", "2h mace", "polearm", "staff"],
    "SHAMAN": ["1h axe", "2h axe", "1h mace", "2h mace", "dagger", "fist", "staff", "shield"],
}


def lua_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    with open(SRC, encoding="utf-8") as f:
        data = json.load(f)
    rows = [r for r in data["items"] if r.get("zone") and r.get("quest")]
    rows.sort(key=lambda r: (r["zone"], r["reqlevel"], r["name"], r["id"]))
    out = [
        "-- QuestWeaponData.lua: weapons that are quest rewards, for the Plan tab's \"Weapon:\" lines.",
        "-- GENERATED by bis/build_quest_weapons.py from bis/quest-weapons.json (Wowhead Forever's item lists, read",
        "-- by bis/tools/wh_quest_weapons.py). Never hand-edit. Credit: Wowhead (https://www.wowhead.com/forever).",
        "-- Row: { itemId, name, kind, requiredLevel, quest, zone, side (0 both / 1 Alliance / 2 Horde), quality }",
        "",
        "local _, R2F = ...",
        "",
        "R2F.QuestWeaponData = {",
        "  source = \"Wowhead\",",
        "  maxLevel = %d," % data.get("maxlevel", 0),
        "  use = {",
    ]
    for cls in sorted(CLASS_USE):
        kinds = [lua_str(k) for k in CLASS_USE[cls]]
        half = (len(kinds) + 1) // 2
        # Two lines per class, so no line is over luacheck's 130 characters.
        out.append("    %s = { %s," % (cls, ", ".join(kinds[:half])))
        out.append("      %s }," % ", ".join(kinds[half:]))
    out += ["  },", "  items = {"]
    for r in rows:
        side = r.get("side") if r.get("side") in (1, 2) else 0
        out.append("    { %d, %s, %s, %d, %s, %s, %d, %d }," % (
            r["id"], lua_str(r["name"]), lua_str(r["type"]), r["reqlevel"], lua_str(r["quest"]), lua_str(r["zone"]),
            side, r.get("quality", 2)))
    out += ["  },", "}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote %s: %d quest weapons" % (os.path.relpath(OUT, ROOT), len(rows)))
    # The site's copy: Alliance and both-faction rows only (the plan is Alliance), with the weapon's dps for ranking.
    site_rows = [[r["id"], r["name"], r["type"], r["reqlevel"], r["quest"], r["zone"], r.get("quality", 2), r.get("dps") or 0]
                 for r in rows if r.get("side") in (None, 0, 1)]
    site = {
        "_about": "GENERATED by bis/build_quest_weapons.py from bis/quest-weapons.json (Wowhead Forever). Never hand-edit. "
                  "item = [itemId, name, kind, requiredLevel, quest, zone, quality, dps]; use = weapon kinds per class.",
        "maxLevel": data.get("maxlevel", 0),
        "use": CLASS_USE,
        "items": site_rows,
    }
    with open(OUT_SITE, "w", encoding="utf-8", newline="\n") as f:
        json.dump(site, f, ensure_ascii=False, separators=(",", ":"))
        f.write("\n")
    print("wrote %s: %d Alliance quest weapons" % (os.path.relpath(OUT_SITE, ROOT), len(site_rows)))


if __name__ == "__main__":
    main()
