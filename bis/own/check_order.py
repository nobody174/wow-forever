"""Cross-check 2: does our own scoring put each slot's three picks (best, 2nd, 3rd) in ForeverDB's order?

Our score = stats read from the Wowhead tooltip x ForeverDB's spec weights (check_scores.py explains the conversions). A slot is listed when
our best of the three is not ForeverDB's best and beats it by more than 10 percent: those are the picks worth a second look. Items whose
Wowhead stats differ from ForeverDB's printed ones (level-scaled items, see README.md) are marked, because for them the disagreement may
be the scaling and not the ranking. Run:  python bis/own/check_order.py > bis/own/report.md
"""
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from check_scores import CONV, RAW, score, weights_of   # noqa: E402
from stats import parse                                  # noqa: E402
from tooltips import get_many                            # noqa: E402


def printed_stats(line):
    out = {}
    for st in line.split(","):
        st = st.strip()
        m = re.match(r"[+−-]?\s?(\d+(?:\.\d+)?)\s+(.+)", st)
        if m:
            out[m.group(2).strip()] = float(m.group(1)) * (-1 if st[0] in "−-" else 1)
    return out


def main():
    specs = {}
    ids = []
    for f in sorted(glob.glob(os.path.join(RAW, "*.json"))):
        d = json.load(open(f, encoding="utf-8"))
        specs[os.path.basename(f)[:-5]] = d
        for s in d["slots"]:
            if s.get("best"):
                ids.append(s["best"]["id"])
                ids += [n["id"] for n in s.get("next", [])]
    tips = get_many(ids, quiet=True)
    rows, slots = [], 0
    for name, d in specs.items():
        w = weights_of(d["weights"])
        for s in d["slots"]:
            b = s.get("best")
            if not b:
                continue
            picks = [(b["id"], b["name"])] + [(n["id"], n["name"]) for n in s.get("next", [])]
            if any(i not in tips for i, _ in picks):
                continue
            slots += 1
            ours = []
            for i, nm in picks:
                st = parse(tips[i]["tooltip"])[0]
                ours.append((score(st, w, CONV, name, s["slot"]), i, nm))
            top = max(ours)
            if top[1] != b["id"] and top[0] > ours[0][0] * 1.10 + 0.5:
                scaled = "<!--sc" in tips[top[1]]["tooltip"] or "<!--sc" in tips[b["id"]]["tooltip"]
                rows.append((name, s["slot"], b["name"], round(ours[0][0], 1), top[2], round(top[0], 1), scaled))
    print("# Mr.BiZ cross-check: our scores against ForeverDB's order\n")
    print("Generated by `python bis/own/check_order.py` from Wowhead's Forever tooltips and ForeverDB's weights (beta build %s)." %
          next(iter(specs.values()))["build"])
    print("%d slots compared, %d where our best of the three is not ForeverDB's best by more than 10 percent.\n" % (slots, len(rows)))
    print("| Spec | Slot | ForeverDB's best (our score) | Our best of the three (our score) | Scaled item involved |")
    print("|---|---|---|---|---|")
    for name, slot, theirs, ts, ours, os_, scaled in rows:
        print("| %s | %s | %s (%s) | %s (%s) | %s |" % (name, slot, theirs, ts, ours, os_, "yes" if scaled else ""))


if __name__ == "__main__":
    main()
