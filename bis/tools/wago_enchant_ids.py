"""Writes bis/enchant_ids.json: for each enchant name professions.html knows, the enchantment id(s) the game puts in an
item link when that enchant is applied (SpellItemEnchantment id). The addon reads the id from your worn item's link, so it
can say which of the listed enchants you already have.

Source: wago.tools' DB2 tables for the Forever beta build (SpellName gives spell ids by name; SpellEffect rows with
Effect 53 = ENCHANT_ITEM_PERMANENT carry the enchantment id in EffectMiscValue_0). Armor kits are items, not spells,
so they get no id (the addon then just says "an armor kit or another enchant").

usage: python bis/tools/wago_enchant_ids.py [build]       (default build below; needs the internet and node)
"""
import csv, io, json, os, subprocess, sys, urllib.request

BUILD = sys.argv[1] if len(sys.argv) > 1 else "1.60.1.70338"
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
OUT = os.path.join(ROOT, "bis", "enchant_ids.json")


def fetch_csv(table):
    url = "https://wago.tools/db2/%s/csv?build=%s" % (table, BUILD)
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=180) as r:
        return list(csv.DictReader(io.StringIO(r.read().decode("utf-8", "replace"))))


def main():
    names = json.loads(subprocess.run(
        ["node", os.path.join(ROOT, "bis", "enchants_from_professions.js"), "--names"],
        capture_output=True, text=True, check=True).stdout)
    spell_ids = {}
    for row in fetch_csv("SpellName"):
        spell_ids.setdefault(row["Name_lang"], []).append(int(row["ID"]))
    enchant_of = {}
    for row in fetch_csv("SpellEffect"):
        if row["Effect"] == "53":
            enchant_of.setdefault(int(row["SpellID"]), []).append(int(row["EffectMiscValue_0"]))
    ids, missing = {}, []
    for name in names:
        found = sorted({e for sid in spell_ids.get(name, []) for e in enchant_of.get(sid, [])})
        if found:
            ids[name] = found
        else:
            missing.append(name)
    out = {
        "_about": "Enchantment id(s) per enchant name (what an item link carries after the enchant is applied). "
                  "Generated by bis/tools/wago_enchant_ids.py from wago.tools DB2 data, Forever beta build %s. "
                  "Names without an id (armor kits, which are items) are listed in `none`." % BUILD,
        "build": BUILD,
        "ids": ids,
        "none": missing,
    }
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
        f.write("\n")
    print("wrote %s: %d names with ids, %d without (%s)" % (OUT, len(ids), len(missing), ", ".join(missing)))


if __name__ == "__main__":
    main()
