# Group ordering used when rendering a spec's macro groups (both HTML and MD).
ORDER = [DPS, HEAL, CLEAN, AUTO, BUFF, PANIC, TARGET, QOL, FOCUS, MISC]

def sort_groups(groups):
    return sorted(groups, key=lambda g: ORDER.index(g["type"]))


# =============================================================================
# Addon data checks: assign stable ids (<CLASS>/<short>, ANY for Universal)
# and fail the build with a clear message on bad short names.
# See ADDON_PLAN.md section 3.2.
# =============================================================================

def class_token(name):
    """English class token as UnitClass would return it, e.g. 'Warrior' -> 'WARRIOR'."""
    return name.upper().replace(" ", "")

def assign_ids_and_validate():
    errors = []
    seen = {}  # (class_token, short) -> name, for per-class+universal uniqueness

    def check(cls_token, m):
        if not m["code"]:
            return  # placeholder entries (e.g. "No dispel") carry no real macro
        short = m.get("short")
        if not short:
            if len(m["name"]) > 16:
                errors.append(
                    f"{cls_token}: macro {m['name']!r} has a body but no `short`, "
                    f"and its name is longer than 16 characters."
                )
            return
        if len(short) > 16:
            errors.append(f"{cls_token}: short name {short!r} is {len(short)} characters, max is 16.")
        key = (cls_token, short)
        if key in seen:
            errors.append(
                f"{cls_token}: short name {short!r} is used by both "
                f"{seen[key]!r} and {m['name']!r}."
            )
        else:
            seen[key] = m["name"]
        m["id"] = f"{cls_token}/{short}"

    for group in UNIVERSAL:
        for m in group["macros"]:
            check("ANY", m)

    for cls in CLASSES:
        token = class_token(cls["name"])
        for section in cls["sections"]:
            for group in section["groups"]:
                for m in group["macros"]:
                    check(token, m)

    if errors:
        print("build.py: macro short-name check failed:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        sys.exit(1)

assign_ids_and_validate()

# =============================================================================
# Addon macro bundle: addon/RoadToForever/MacroData.lua holds EVERY macro as one import string
# (the same R2F1: format the site's export tray writes, with K records), so the addon installs
# the whole library by itself and the Import window is only for custom picks. Same record order
# as template.html's XINDEX (Universal, then classes; sections; groups in ORDER).
# `python build.py --check-macro-data` only compares the file with data.py (exit 1 if stale).
# =============================================================================
import base64
import hashlib

def macro_import_string():
    strip = lambda v: str(v if v is not None else "").replace("\x1e", "").replace("\x1f", "")
    recs, per_class = [], {}
    everything = [("Universal", None, [{"spec": "Universal", "groups": UNIVERSAL}])]
    everything += [(c["name"], class_token(c["name"]), c["sections"]) for c in CLASSES]
    for _name, _tok, sections in everything:
        for sec in sections:
            for g in sort_groups(sec["groups"]):
                for m in g["macros"]:
                    if not m.get("code") or not m.get("id"):
                        continue
                    token = m["id"][:m["id"].index("/")]
                    per_class.setdefault(token, []).append(m["id"])
                    recs.append("\x1f".join(strip(v) for v in (
                        m["id"], token, sec["spec"], g["type"], m["name"], m["short"],
                        m.get("icon") or "", m["code"], m.get("note") or "")))
    for token, ids in per_class.items():
        if any("," in i for i in ids):
            sys.exit("build.py: macro id with a comma: K records need another separator")
        recs.append("\x1f".join(("K", token, ",".join(ids))))
    text = "v=1\n" + "\x1e".join(recs)
    return "R2F1:" + base64.b64encode(text.encode("utf-8")).decode("ascii"), len(recs) - len(per_class)

def macro_data_lua():
    string, count = macro_import_string()
    version = hashlib.sha1(string.encode("ascii")).hexdigest()[:12]
    chunks = [string[i:i + 110] for i in range(0, len(string), 110)]
    body = ",\n".join('    "%s"' % c for c in chunks)
    return (
        "-- MacroData.lua: every macro of the site as one import string (R2F1:, see Import.lua).\n"
        "-- GENERATED by build.py from data.py. Never hand-edit: change data.py and run `python build.py`\n"
        "-- (the addon tests fail if this file is stale). Bundle.lua installs it.\n\n"
        "local _, R2F = ...\n\n"
        "R2F.MacroData = {\n"
        '  version = "%s",\n'
        "  count = %d,\n"
        "  string = table.concat({\n%s,\n  }),\n"
        "}\n" % (version, count, body)
    )

MACRO_DATA_PATH = "addon/RoadToForever/MacroData.lua"
if "--check-macro-data" in sys.argv:
    try:
        stale = open(MACRO_DATA_PATH, encoding="utf-8").read() != macro_data_lua()
    except FileNotFoundError:
        stale = True
    sys.exit(1 if stale else 0)

# Example patterns shown at the top of the markdown cheatsheet, one per macro style.
INTRO_RULES = [
    ("Damage (Priest — target-of-target aware)", dps("SPELL")),
    ("Damage (every other class)", dpsHarm("SPELL")),
    ("Mouseover heal / utility (adds self fallback)", heal("SPELL")),
    ("Friend-or-foe, e.g. Dispel Magic (adds self fallback)", util("SPELL")),
    ("Buffs (adds self fallback)", buff("SPELL")),
    ("Spam-safe channel", chan("SPELL")),
    ("Wand", WAND),
]


# =============================================================================
# Markdown build (wow-forever-macros.md)
# =============================================================================

def macro_markdown(m):
    """Render one macro entry as markdown: name + note line, then a code block."""
    if not m["code"]:
        return f"*{m['note']}*\n"
    heading = f"**{m['name']}**"
    if m.get("short"):
        heading += f" (`{m['short']}`)"
    if m["note"]:
        heading += f" — {m['note']}"
    return f"{heading}\n```\n{m['code']}\n```\n"


md = []
md.append("# WoW Forever Macro Cheatsheet (nobody174 style)\n")
md.append(
    "Copy/paste macros for Priest, Shaman, Paladin, Warlock, Hunter and Warrior. "
    "Each class has a **Shared** section (every spec uses it) plus spec-only extras.\n"
)

md.append("## Patterns\n")
for name, code in INTRO_RULES:
    md.append(f"**{name}**\n```\n{code}\n```\n")

md.append("## Notes\n")
md.append(
    "- Spells without a rank cast your highest rank automatically.\n"
    "- Buff, heal/utility and friend-or-foe macros all add `[@player]` as a last "
    "fallback, so they hit you instead of doing nothing with no target. Delete it "
    "if you want the strict targeting-only style.\n"
    "- Item macros (`/use ...`) need the item name edited to the rank you carry.\n"
    "- WoW Forever changes some classes/systems; if a spell name is renamed or missing "
    "in beta, swap the name and keep the pattern.\n"
    "- Macro limit is 255 characters; every macro here fits.\n"
)

md.append("## Universal (all classes)\n")
for group in UNIVERSAL:
    md.append(f"### {group['type']}\n")
    for m in group["macros"]:
        md.append(macro_markdown(m))

for cls in CLASSES:
    md.append(f"## {cls['name']}\n")
    for section in cls["sections"]:
        title = section["spec"] + " (all specs)" if section["spec"] in ("Shared", "General") else section["spec"]
        md.append(f"### {cls['name']} — {title}\n")
        for group in sort_groups(section["groups"]):
            md.append(f"#### {group['type']}\n")
            for m in group["macros"]:
                md.append(macro_markdown(m))

with open("wow-forever-macros.md", "w", encoding="utf-8") as f:
    f.write("\n".join(md))


# =============================================================================
# HTML build (macros.html)
# =============================================================================

payload = {
    "universal": {
        "name": "Universal",
        "color": "#FFD100",
        "sections": [{"spec": "All classes", "groups": UNIVERSAL}],
    },
    "classes": CLASSES,
    "order": ORDER,
    "patterns": [{"name": name, "code": code} for name, code in INTRO_RULES],
}

with open("template.html", encoding="utf-8") as f:
    template = f.read()

html = (
    template
    .replace("__DATA__", json.dumps(payload))
    .replace("__PAGE_MACROS__", 'aria-current="page"')
    .replace("__PAGE_BUILDS__", "")
    .replace("__PAGE_ADDONS__", "")
    .replace("__PAGE_LAUNCH__", "")
)

with open("macros.html", "w", encoding="utf-8") as f:
    f.write(html)

print("built")


